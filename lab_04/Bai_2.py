n = int(input("Nhập số nguyên dương n: "))
while n <= 0:
    n = int(input("Vui lòng nhập số nguyên dương: "))
S1 = 0
S2 = 0
S3 = 0
i = 1
# a) S1 = 1 - 1/2 + 1/3 - 1/4 + 1/5 - ...
while i <= n:
    S1 += ((-1) ** (i + 1)) * (1 / i)
    i += 1
i = 1
# b) S2 = 1/2 + 1/(2×3) + 1/(3×4) + ...
while i <= n:
    S2 += 1 / (i * (i + 1))
    i += 1
i = 2
# c) S3 = 1² + 1³ + 1⁴ + 1⁵ + ...
while i <= n + 1:
    S3 += 1 ** i
    i += 1
print(f"Tổng S1 = {S1}")
print(f"Tổng S2 = {S2}")
print(f"Tổng S3 = {S3}")